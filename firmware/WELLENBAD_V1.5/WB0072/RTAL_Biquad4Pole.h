static inline __attribute__((always_inline)) float rtalClampF(float x, float lo, float hi) {
  return x < lo ? lo : (x > hi ? hi : x);
}

static inline __attribute__((always_inline)) float rtalBiquadProcessF32(
    float x, const RTALBiquadCoeffF &c, float &z1, float &z2) {
  // WB0062 OPT2: symmetric LP numerator. b2==b0 and b1 differs from 2*b0
  // only by sub-float/Q30 rounding noise. Reuse b0*x: 3 instead of 5
  // floating-point multiplies per 2-pole stage.
  const float bx = c.b0 * x;
  float y = bx + z1;
  const float nz1 = (bx + bx) - c.a1 * y + z2;
  const float nz2 = bx - c.a2 * y;

  z1 = nz1;
  z2 = nz2;

  // One output guard per stage remains; WB0061 clamped y,z1,z2 separately.
  if (y > 131071.0f) y = 131071.0f;
  else if (y < -131071.0f) y = -131071.0f;
  return y;
}
